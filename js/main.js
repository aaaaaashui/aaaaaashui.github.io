const interestSubpages = ["game.html", "music.html", "sport.html", "travel.html", "movie.html"];

function currentFile() {
  return location.pathname.split("/").pop() || "index.html";
}

function currentLang() {
  return localStorage.getItem("site-lang") === "en" ? "en" : "zh";
}

function applyLang(lang) {
  const t = dict[lang];
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (t[key]) el.innerHTML = t[key];
  });
  document.documentElement.lang = lang === "en" ? "en" : "zh-CN";
  const btn = document.getElementById("lang-switch");
  if (btn) btn.textContent = t.langBtn;
  const file = currentFile();
  if (t.titles[file]) document.title = t.titles[file];
}

function bindLangSwitch() {
  const btn = document.getElementById("lang-switch");
  if (btn) {
    btn.addEventListener("click", () => {
      const next = currentLang() === "zh" ? "en" : "zh";
      localStorage.setItem("site-lang", next);
      location.reload();
    });
  }
}

function mountChrome() {
  const file = currentFile();
  const lang = currentLang();
  const t = dict[lang];

  // 落地页（首页）：不显示导航，只放一个悬浮的语言切换
  if (file === "index.html") {
    const toggle = document.createElement("button");
    toggle.className = "lang-switch lang-switch-float";
    toggle.id = "lang-switch";
    toggle.type = "button";
    toggle.textContent = t.langBtn;
    document.body.prepend(toggle);
    bindLangSwitch();
    return;
  }

  const activeTarget = interestSubpages.includes(file) ? "interests.html" : file;
  const nav = pages
    .map(([href, key]) => {
      const active = activeTarget === href ? " active" : "";
      return `<a class="${active.trim()}" href="${href}" data-transition="v">${t[key]}</a>`;
    })
    .join("");

  const header = document.createElement("header");
  header.className = "topbar";
  header.innerHTML = `
    <div class="shell topbar-inner">
      <a class="brand" href="index.html">
        <span class="mark">雨</span>
        <span data-i18n="brand">${t.brand}</span>
      </a>
      <nav>${nav}</nav>
      <button class="lang-switch" id="lang-switch" type="button">${t.langBtn}</button>
    </div>
  `;

  const footer = document.createElement("footer");
  footer.innerHTML = `<div class="shell" data-i18n="footer">${t.footer}</div>`;

  document.body.prepend(header);
  document.body.append(footer);

  bindLangSwitch();
}

function tryLocalImage(img) {
  const exts = ["png", "jpeg", "webp"];
  const base = img.src.replace(/\.(jpg|jpeg|png|webp)$/i, "");
  let i = 0;
  let settled = false;

  const onLoad = () => {
    if (settled) return;
    if (img.naturalWidth > 0) {
      settled = true;
      if (img.parentElement) img.parentElement.classList.add("has-photo");
    }
  };
  const onError = () => {
    if (settled) return;
    if (i < exts.length) {
      img.src = base + "." + exts[i++];
    } else {
      settled = true;
      img.remove();
    }
  };

  img.addEventListener("load", onLoad);
  img.addEventListener("error", onError);

  if (img.complete) {
    if (img.naturalWidth > 0) onLoad();
    else onError();
  }
}

function fallbackCopy(text) {
  const ta = document.createElement("textarea");
  ta.value = text;
  ta.style.position = "fixed";
  ta.style.opacity = "0";
  document.body.appendChild(ta);
  ta.focus();
  ta.select();
  let ok = false;
  try {
    ok = document.execCommand("copy");
  } catch (e) {}
  document.body.removeChild(ta);
  return ok;
}

function copyText(text) {
  return new Promise((resolve) => {
    if (navigator.clipboard && window.isSecureContext) {
      navigator.clipboard
        .writeText(text)
        .then(() => resolve(true))
        .catch(() => resolve(fallbackCopy(text)));
    } else {
      resolve(fallbackCopy(text));
    }
  });
}

